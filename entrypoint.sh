#!/bin/sh
# Контейнер стартует от root, чтобы иметь возможность выставить правильного
# владельца для /app/data — это может быть как именованный docker volume,
# так и локальный каталог с хоста (bind mount), примонтированный от имени
# произвольного UID хост-системы. После этого процесс сервиса запускается
# от непривилегированного пользователя app (см. su-exec ниже).
set -e

mkdir -p /app/data/downloads
chown -R app:app /app/data

exec su-exec app "$@"
